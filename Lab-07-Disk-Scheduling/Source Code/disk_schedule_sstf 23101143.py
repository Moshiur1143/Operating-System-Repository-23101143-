#Unordered
requests = [3,60,10,25,30,4]
Head = 41
total = 0
n = len(requests)
order=[Head]

while requests:
  nearest = min(requests, key = lambda r : abs(r-Head))
  total += abs(nearest - Head)
  Head = nearest
  order.append(Head)
  requests.remove(nearest)


print("-->".join(map(str,order)))
print("Total Head Movement =",total)

