def fcfs(processes):
    procs = sorted(processes, key=lambda x: x[1])  # sort by AT
    time = 0
    result = []
    for pid, at, bt in procs:
        start = max(time, at)
        ct = start + bt
        tat = ct - at
        wt = tat - bt
        result.append([pid, at, bt, ct, tat, wt])
        time = ct
    return result


