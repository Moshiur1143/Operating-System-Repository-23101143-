def sjf_non_preemptive(processes):

    n = len(processes)
    completed = 0
    current_time = 0
    is_done = [False] * n
    result = []

    while completed != n:
        idx = -1
        min_bt = float('inf')

        for i in range(n):
            pid, at, bt = processes[i]
            if at <= current_time and not is_done[i]:
                if bt < min_bt:
                    min_bt = bt
                    idx = i
                if bt == min_bt and at < processes[idx][1]:
                    idx = i

        if idx == -1:

            current_time += 1
            continue

        pid, at, bt = processes[idx]
        current_time += bt
        ct = current_time
        tat = ct - at
        wt = tat - bt

        result.append([pid, at, bt, ct, tat, wt])
        is_done[idx] = True
        completed += 1

    return result



